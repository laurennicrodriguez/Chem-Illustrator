"""Make src/text/font-widths.ts: the width of every character in the Liberation fonts.

The Liberation fonts (SIL Open Font License 1.1) are made to have exactly the widths of
Times New Roman, Arial and Courier New, so documents laid out with these numbers break their
lines in the same places on every computer, in the PDF, and in Word.

Run with Python 3 and fontTools (pip install fonttools):
    python scripts/font-widths.py /usr/share/fonts/truetype/liberation
Only the widths are taken; no part of the fonts themselves is copied.
"""

import sys
from pathlib import Path

from fontTools.ttLib import TTFont

FAMILIES = {
    'serif': 'LiberationSerif',
    'sans': 'LiberationSans',
    'mono': 'LiberationMono',
}
STYLES = {'': 'Regular', 'b': 'Bold', 'i': 'Italic', 'bi': 'BoldItalic'}

# Characters a chemistry document uses: Latin, Greek, punctuation, super- and subscript
# digits, letter-like signs (Å, ℃), arrows and maths.
RANGES = [(0x20, 0x7E), (0xA0, 0x17F), (0x370, 0x3FF), (0x2000, 0x206F), (0x2070, 0x209F),
          (0x2100, 0x214F), (0x2190, 0x21FF), (0x2200, 0x22FF), (0x25A0, 0x25FF)]


def widths(path: Path) -> tuple[int, dict[int, int]]:
    font = TTFont(path)
    upem = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font['hmtx']
    out = {}
    for a, b in RANGES:
        for c in range(a, b + 1):
            g = cmap.get(c)
            if g is not None:
                out[c] = hmtx[g][0]
    return upem, out


def encode(w: dict[int, int]) -> str:
    """Runs of neighbouring characters: "start:w,w,w;start:w…" (start in hex)."""
    parts = []
    run_start = None
    run = []
    prev = None
    for c in sorted(w):
        if prev is not None and c == prev + 1:
            run.append(w[c])
        else:
            if run:
                parts.append(f'{run_start:x}:' + ','.join(map(str, run)))
            run_start, run = c, [w[c]]
        prev = c
    if run:
        parts.append(f'{run_start:x}:' + ','.join(map(str, run)))
    return ';'.join(parts)


def main() -> None:
    folder = Path(sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/liberation')
    tables = {}
    upems = set()
    for fam, base in FAMILIES.items():
        for key, style in STYLES.items():
            upem, w = widths(folder / f'{base}-{style}.ttf')
            upems.add(upem)
            tables[fam + key] = encode(w)
    assert len(upems) == 1, upems
    upem = upems.pop()
    lines = [
        '// Generated by scripts/font-widths.py: do not edit by hand.',
        '// Character widths of the Liberation fonts (SIL Open Font License 1.1, see THIRD-PARTY-NOTICES.md),',
        '// which have the same widths as Times New Roman, Arial and Courier New. Units per em: ' + str(upem) + '.',
        '// Each table is runs of neighbouring characters: "start (hex):width,width,…;…".',
        '',
        f'export const UNITS_PER_EM = {upem};',
        '',
        'export const WIDTH_TABLES: Record<string, string> = {',
    ]
    for k, v in tables.items():
        lines.append(f"  '{k}': '{v}',")
    lines.append('};')
    lines.append('')
    out = Path(__file__).resolve().parent.parent / 'src' / 'text' / 'font-widths.ts'
    out.write_text('\n'.join(lines), encoding='utf-8')
    print(out, sum(len(v) for v in tables.values()), 'characters of tables')


if __name__ == '__main__':
    main()
